import * as THREE from 'three';
import {
    DEFAULT_SIZE, DEFAULT_SEGMENTS, sampleHeight, waterSurface, tileSeed,
    matchEdges, matchWater, seamBand
} from './environment/elements.js';
import { buildEnvironment, getEnvironment, DEFAULT_ENVIRONMENT_ID } from './environment/presets.js';
import { animateWater } from './water.js';
import { updateNormals } from './terrain-normals.js';
import {
    TILE_REACH, tileIndexAt, tileKey, tileBounds, tileCenter, tilesInReach,
    tileWorthKeeping, sameTile, isHomeTile, tilesTouching
} from './world-tiles.js';
import { recordWorld, sameWorld } from './world-record.js';

/**
 * The ground, as the mesh side of an assembled environment. Everything about
 * the world's shape and colour is generated by `js/environment/`, which knows
 * nothing about Three.js; this class turns the field it hands back into
 * geometry and answers the height queries the flight model asks.
 *
 * The world has no end to it. The square an environment describes is one tile
 * of an endless grid of them, each tile that description seeded from its own
 * place in the grid, and the tiles around the aircraft are drawn out past
 * everything the camera can see - so the ground the fog was promising is
 * actually there, and the edge that used to be at the end of it can never be
 * flown to. `js/world-tiles.js` is the arithmetic of that grid; this class is
 * what draws it.
 */
export class Terrain {
    constructor(scene, environmentId = DEFAULT_ENVIRONMENT_ID, world = {}) {
        this.scene    = scene;
        this.size     = DEFAULT_SIZE;
        this.segments = DEFAULT_SEGMENTS;
        this.built    = null;

        // The tiles on screen, by their place in the grid, and the tile the
        // aircraft is over - which is the one every world question that names no
        // place is answered from.
        this.tiles = new Map();
        this.focus = { x: 0, z: 0 };

        // How long the water has been moving. Time the flight did not spend
        // flying is time the surface does not spend running, so a paused world
        // is a still one. Held for the world rather than for a tile, because the
        // swell is a function of where a point is rather than of which tile it
        // is on, and two tiles that agree on the time meet at the same surface.
        this.time = 0;

        this.setEnvironment(environmentId, world);

        // The first world is drawn whole rather than filled in over the frames
        // that follow, because those frames are the ones the loading screen is
        // waiting on: what it comes off to reveal should be a world rather than
        // a corner of one.
        this.drawTiles(0, 0, Infinity);
    }

    /**
     * Flies a different world. Every tile drawn is released rather than left in
     * the scene, so switching environments from the settings panel does not
     * stack them up behind each other.
     *
     * A world is more than the preset it is drawn from: the same description
     * seeded differently, with a strip in it rather than without one, or with
     * an element's range moved, is a different world and is rebuilt as one.
     * What is not rebuilt is asking for the world already on screen, which is
     * what keeps the panel from regenerating the ground every time a setting
     * near it is touched.
     *
     * `elements` is the placements to draw instead of the ones the preset
     * describes, which is what the element editor hands over: an edited world
     * is a description like any other, so it goes through the same generator
     * the preset's does rather than down a path of its own.
     *
     * Returns true when the world actually changed.
     */
    setEnvironment(environmentId, world = {}) {
        const environment = getEnvironment(environmentId);
        const asked = {
            id: environment.id,
            seed: world.seed ?? environment.seed,
            runway: world.runway ?? false,
            base: world.base ?? null,
            elements: world.elements ?? null
        };

        if (this.tiles.size > 0 && sameWorld(this.built, asked)) return false;

        // The world is recorded as a copy of the ask rather than as the ask
        // itself, so a caller that goes on editing the description it handed
        // over is not editing this record too. `js/world-record.js` is that
        // copy and the comparison above; both are kept out of here so they can
        // be tested without a renderer.
        this.built       = recordWorld(asked);
        this.environment = environment;
        this.maxHeight   = asked.base?.maxHeight ?? environment.base?.maxHeight ?? 480;

        // A new world is a new flight, which opens over the middle tile: the
        // ground is laid out from there rather than from wherever the last
        // flight had wandered to. Only the tile the flight opens on is drawn
        // here; the ground out to the horizon fills in over the frames that
        // follow, so changing world costs a few slow frames rather than one
        // long stall with nothing on screen.
        this.release();
        this.focus = { x: 0, z: 0 };
        this.drawTiles(0, 0);

        return true;
    }

    /**
     * Draws the ground around a point and releases the ground far behind it.
     * The tile the point is over is always drawn before this returns, because
     * it is the ground the aircraft is about to be measured against; the tiles
     * beyond it are drawn a few at a time, `budget` of them per call, so a
     * crossing costs a frame or two rather than a stall.
     *
     * Returns true when the point moved onto a different tile.
     */
    focusOn(x, z, budget = 1) {
        const here  = tileIndexAt(x, z, this.size);
        const moved = !sameTile(here, this.focus);

        this.focus = here;
        this.drawTiles(x, z, budget);

        return moved;
    }

    /**
     * Lays the tiles in reach of a point and lets go of the ones out of it.
     * Nearest first, so a budget that runs out leaves the ground the aircraft
     * is closest to needing drawn and the ground beyond it for the next frame.
     */
    drawTiles(x, z, budget = 1) {
        // The ground the aircraft is over is never on a budget: an aircraft
        // measured against ground that has not been generated is an aircraft
        // flying at sea level over a world it cannot see.
        this.addTile(tileIndexAt(x, z, this.size));

        let spent = 0;
        for (const index of tilesInReach(x, z, this.size, TILE_REACH)) {
            if (this.tiles.has(tileKey(index))) continue;
            if (spent >= budget) break;
            this.addTile(index);
            spent++;
        }

        for (const [key, tile] of this.tiles) {
            // The middle tile is never released. It is the world the flight was
            // configured over and the one carrying the strip, so a question
            // about the runway has an answer however far the aircraft has flown
            // from it.
            if (isHomeTile(tile.index)) continue;
            if (tileWorthKeeping(tile.index, x, z, this.size)) continue;
            this.dropTile(key, tile);
        }
    }

    /**
     * Generates and draws one tile of the world, or leaves the one already
     * there alone. Only the middle tile carries the strip a world was asked
     * for: a runway is a place in the world rather than a feature of the ground
     * that repeats across it, and a landing is on that strip or on none.
     *
     * The tile is settled against the tiles already laid beside it before it is
     * drawn, so the world has no join anywhere in it. That has to happen here
     * rather than as a pass over the world afterwards, because a tile is added
     * one at a time and the one being added is the only one whose edges are new.
     */
    addTile(index) {
        const key = tileKey(index);
        if (this.tiles.has(key)) return this.tiles.get(key);

        const home   = isHomeTile(index);
        const middle = tileCenter(index, this.size);
        const field  = buildEnvironment(this.environment, {
            size: this.size,
            segments: this.segments,
            seed: tileSeed(this.built.seed, index.x, index.z),
            base: this.built.base,
            elements: tileElements(this.built.elements, home),
            runway: home ? this.built.runway : false,
            originX: middle.x,
            originZ: middle.z
        });

        // Settled before the mesh is built, so the new tile is drawn once from
        // ground that has already been matched rather than drawn and corrected.
        const settled = this.joinTile(field, index);

        const tile = { index, field, mesh: buildMesh(field), water: waterSurface(field), watered: false };
        this.scene.add(tile.mesh);
        this.tiles.set(key, tile);

        for (const neighbour of settled) redrawTile(neighbour);

        // The water is settled last, once every surface this join rebuilt
        // exists. `matchEdges` leaves the ground under it agreeing exactly, so
        // the height it rests at and the colour it is painted already match at
        // a join; what does not is how open each tile alone makes the water
        // there, which is what the swell and the glint are both scaled by.
        if (settled.length > 0) {
            const assembly = this.waterAssembly([tile, ...settled]);

            // Every tile the settling reached is marked unwatered, for the
            // reason `redrawTile` marks the ones it drew. The assembly is wider
            // than the redraws, and a paused world writes a tile's water once
            // and skips it after, so a tile settled here and left marked keeps
            // drawing the openness it worked out alone until the flight runs
            // again - which is the join this pass is here to close.
            if (matchWater(assembly.map(each => each.water)) > 0) {
                for (const each of assembly) each.watered = false;
            }
        }

        return tile;
    }

    /**
     * The tiles whose water a join may have unsettled: those handed over, and
     * every tile touching one of them.
     *
     * Wider than the tiles the join moved, because `redrawTile` reads a
     * surface off its field again and so puts back the openness one tile alone
     * works out - at every join that tile is on, not only at the one with the
     * tile just laid. A neighbour redrawn here also meets the tiles further
     * out, and those joins were settled on a frame that is over.
     */
    waterAssembly(tiles) {
        const found = new Map();

        for (const tile of tiles) {
            found.set(tileKey(tile.index), tile);
            for (const place of tilesTouching(tile.index)) {
                const key = tileKey(place);
                const neighbour = this.tiles.get(key);
                if (neighbour) found.set(key, neighbour);
            }
        }

        const wet = [];
        for (const tile of found.values()) if (tile.water) wet.push(tile);

        return wet;
    }

    /**
     * Settles a field about to be laid at a place in the grid against every
     * tile already drawn beside it, so what an element drew up to one tile's
     * edge meets what its neighbour drew at theirs.
     *
     * The base ground was always seamless, because it is noise sampled at world
     * coordinates and runs on across a join whatever tile draws it. What did not
     * run on is the elements, which are placed from a per-tile seed: a peak
     * whose radius reaches past the edge was raised on one side of it and not
     * the other, and that is the join this closes.
     *
     * Every neighbour is handed over at once rather than one at a time, for the
     * reason the Matter API's `join` does it that way: a vertex four tiles all
     * reach has to be settled against all four of them to close, and settling it
     * twice against two of them leaves a corner that agrees with neither.
     *
     * Costs nothing per frame beyond the tile being added - no tile is read that
     * is not touching it - so the budget `drawTiles` spends is the budget it
     * always was.
     *
     * Returns the tiles whose own ground moved, which are the ones that have to
     * be drawn again.
     */
    joinTile(field, index) {
        const touching = [];
        for (const place of tilesTouching(index)) {
            const tile = this.tiles.get(tileKey(place));
            if (tile) touching.push(tile);
        }

        if (touching.length === 0) return [];
        if (matchEdges([field, ...touching.map(tile => tile.field)]) === 0) return [];

        return touching;
    }

    /** Takes one tile out of the scene and gives back everything it held. */
    dropTile(key, tile) {
        this.scene.remove(tile.mesh);
        tile.mesh.geometry.dispose();
        tile.mesh.material.dispose();
        this.tiles.delete(key);
    }

    /** Takes the whole world out of the scene, tile by tile. */
    release() {
        for (const [key, tile] of this.tiles) this.dropTile(key, tile);
    }

    /** The tile a place in the world is on, or null for ground not drawn. */
    tileAt(x, z) {
        return this.tiles.get(tileKey(tileIndexAt(x, z, this.size))) ?? null;
    }

    /** The field of the tile the aircraft is over, which is the world it is in. */
    get field() {
        return this.tiles.get(tileKey(this.focus))?.field ?? null;
    }

    /** The strips the world being flown carries, for anything landing on one. */
    getRunways() {
        return this.tiles.get(tileKey({ x: 0, z: 0 }))?.field.runways ?? [];
    }

    /** The one strip a world carries, or null for a world generated without one. */
    getRunway() {
        return this.getRunways()[0] ?? null;
    }

    /**
     * Moves the water on by a frame, across every tile drawn. The land is drawn
     * once and lit by the sun; the water is the one part of the world that is
     * never still, and the one part that shines, so it is the only part written
     * again after the ground was built.
     *
     * `light` is how much day there is to glint off it, so a surface under a
     * night sky goes flat and dark rather than sparkling under a sun that is
     * not there.
     *
     * Returns how many vertices moved.
     */
    updateWater(dt = 0, light = 1) {
        this.time += dt;

        let moved = 0;
        for (const tile of this.tiles.values()) {
            if (!tile.water) continue;
            if (dt === 0 && tile.watered) continue;

            const position = tile.mesh.geometry.attributes.position;
            const color    = tile.mesh.geometry.attributes.color;

            moved += animateWater(tile.water, this.time, {
                positions: position.array,
                colors: color.array,
                light
            });

            position.needsUpdate = true;
            color.needsUpdate = true;
            tile.watered = true;
        }

        return moved;
    }

    /**
     * The height of the ground anywhere in the world. Ground too far out to
     * have been drawn reads as sea level, the way ground outside a world always
     * did - but it is never ground the aircraft is over, because the tile under
     * it is drawn before it gets there.
     */
    getTerrainHeightAt(x, z) {
        const tile = this.tileAt(x, z);
        return tile ? sampleHeight(tile.field, x, z) : 0;
    }

    /**
     * The square the aircraft is flying over. The world itself has no bounds to
     * report, so what a chart is drawn to is the tile in force: crossing into
     * the next one is a new square rather than the end of the only one.
     */
    getBounds() {
        return tileBounds(this.focus, this.size);
    }
}

/** The mesh one field is drawn as, standing where the field says it does. */
function buildMesh(field) {
    const geo = new THREE.PlaneGeometry(field.size, field.size, field.segments, field.segments);
    geo.rotateX(-Math.PI / 2);

    // The mesh is drawn where the field says it is rather than moved there
    // afterwards, so a vertex stands at the world coordinate the generator
    // wrote it at - which is the coordinate the water pass writes back to.
    if (field.originX !== 0 || field.originZ !== 0) {
        geo.translate(field.originX, 0, field.originZ);
    }

    // The field is sampled in the same row-by-row order the plane lays its
    // vertices out in, so the heights and colours drop straight in.
    const pos = geo.attributes.position;
    for (let i = 0; i < pos.count; i++) {
        pos.setY(i, field.height[i]);
    }

    geo.setAttribute('color', new THREE.Float32BufferAttribute(field.color.slice(), 3));
    geo.computeVertexNormals();

    return new THREE.Mesh(geo, new THREE.MeshLambertMaterial({ vertexColors: true }));
}

/**
 * Draws a tile again from the field as it now stands, for a tile whose ground
 * was moved by a join after it was laid.
 *
 * The geometry it is already drawn with is written into rather than replaced. A
 * tile settled against a new neighbour has had a few vertices either side of one
 * edge moved and nothing else touched, so building a whole plane and disposing
 * the old one would spend the cost of generating a tile to redraw a strip of it -
 * on a frame that is already generating a tile.
 *
 * The water is recorded again rather than kept. Its resting heights and colours
 * are read off the finished field, so a surface recorded before the join is a
 * surface resting on ground that has since moved, and the vertices at or under
 * the level are not necessarily the same ones. `watered` comes off with it so a
 * paused world - where the water pass returns early on a tile already written -
 * still puts the surface back over the ground that moved underneath it.
 */
function redrawTile(tile) {
    const { field, mesh } = tile;
    const position = mesh.geometry.attributes.position;
    const color    = mesh.geometry.attributes.color;

    for (let i = 0; i < field.count; i++) position.setY(i, field.height[i]);
    color.array.set(field.color);

    position.needsUpdate = true;
    color.needsUpdate = true;
    relightSeam(mesh.geometry, field);

    tile.water   = waterSurface(field);
    tile.watered = false;

    return tile;
}

/**
 * Lights the ground again where the join moved it, rather than over the whole
 * plane of a tile.
 *
 * `computeVertexNormals` walks all 201 by 201 of a tile, and the join it is
 * being called for moved three vertices in from one edge - so it spent most of
 * what writing into the geometry rather than rebuilding it was meant to save.
 * Measured in a browser across the ten presets, laying a tile beside others
 * cost 58.5ms against 46.9ms for one laid alone, and the band brings that to
 * 50.2ms: about seven tenths of what the join was adding.
 *
 * A field with no seam recorded on it - nothing settled against it, or a field
 * from before the record existed - is lit the way it always was. So is a
 * geometry with no index or no normals, which is not a plane this can walk the
 * faces of.
 */
function relightSeam(geometry, field) {
    const moved  = seamBand(field);
    const normal = geometry.attributes.normal;

    if (!moved || !normal || !geometry.index) {
        geometry.computeVertexNormals();
        return;
    }

    updateNormals({
        positions: geometry.attributes.position.array,
        normals: normal.array,
        index: geometry.index.array,
        moved
    });

    normal.needsUpdate = true;
}

/**
 * The placements one tile is drawn from, for a world described by placements
 * rather than by a preset. The strip comes off every tile but the middle one,
 * for the reason it was only ever laid on that one: a runway is a place in the
 * world rather than a feature of the ground that repeats across it, and a
 * description handed whole to every tile would cut a strip into all nine.
 *
 * Nothing at all for a world drawn from its preset, which is the case the
 * generator already answers from the environment itself.
 */
function tileElements(elements, home) {
    if (!elements) return undefined;
    return home ? elements : elements.filter(placement => placement.type !== 'runway');
}

